/**
 * تابع جستجوی هوشمند دو زبانه و بدون حساسیت به حروف کوچک/بزرگ
 */
export function searchPortal(query: string, lang: Language): SearchItem[] {
  const clean = query.trim().toLowerCase();
  if (!clean || clean.length < 2) return [];

  const tokens = clean.split(/\s+/).filter(Boolean);

  return SEARCH_INDEX.filter((item) => {
    const haystack = [
      item.titleFa,
      item.titleEn,
      item.descFa,
      item.descEn,
      item.categoryFa,
      item.categoryEn,
      item.badge || '',
      ...(item.keywords || []),
    ]
      .join(' ')
      .toLowerCase();

    // تمام توکن‌ها باید در متن یافت شوند
    return tokens.every((token) => haystack.includes(token));
  }).slice(0, 10);
}
